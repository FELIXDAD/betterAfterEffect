#!/usr/bin/env python3
"""Copy the agent guide into the bae-animation skill as reference files.

The source of truth is docs/agent-guide/. The skill must be self-contained
(it is installed by copying skills/bae-animation/ somewhere else), so the
guide chapters are copied into skills/bae-animation/references/.

The eval set (docs/agent-guide/evals/) is deliberately NOT copied: an agent
under evaluation must not see the expected results. Links that point to files
which are not copied are turned into plain text.

Usage:
    python3 skills/sync-references.py          # regenerate references/
    python3 skills/sync-references.py --check  # exit 1 if references/ is stale
"""

import argparse
import posixpath
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "docs" / "agent-guide"
TARGET = REPO / "skills" / "bae-animation" / "references"

# Files copied into the skill, relative to SOURCE. Order does not matter.
INCLUDE = [
    "01-concepts.md",
    "02-workflow.md",
    "03-animation.md",
    "04-storyboard.md",
    "05-collaboration.md",
    "06-quality.md",
    "08-mistakes.md",
    "tools.md",
    "recipes/README.md",
    "recipes/title-in.md",
    "recipes/lower-third.md",
    "recipes/logo-reveal.md",
    "recipes/data-chart.md",
    "recipes/ui-motion.md",
    "recipes/animatic.md",
    "recipes/handoff-ae.md",
]

HEADER = (
    "<!-- Generated by skills/sync-references.py from docs/agent-guide/{name}. "
    "Do not edit; edit the source and re-run the script. -->\n\n"
)

LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def rewrite_links(text: str, name: str) -> str:
    """Keep links to copied files; flatten links to anything else into text."""
    included = set(INCLUDE)
    base = posixpath.dirname(name)

    def replace(match: "re.Match[str]") -> str:
        label, target = match.group(1), match.group(2)
        if re.match(r"^[a-z]+:", target):  # external URL
            return match.group(0)
        path = target.split("#", 1)[0]
        if not path:  # same-file anchor
            return match.group(0)
        resolved = posixpath.normpath(posixpath.join(base, path))
        if resolved in included:
            return match.group(0)
        return f"{label}（BAE 仓库 docs/agent-guide/{resolved}）"

    return LINK.sub(replace, text)


def render(name: str) -> str:
    text = (SOURCE / name).read_text(encoding="utf-8")
    return HEADER.format(name=name) + rewrite_links(text, name)


def expected_files() -> dict:
    return {TARGET / name: render(name) for name in INCLUDE}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only verify, do not write")
    args = parser.parse_args()

    expected = expected_files()
    existing = {p for p in TARGET.rglob("*.md")} if TARGET.exists() else set()
    stale = sorted(
        str(p.relative_to(REPO))
        for p, content in expected.items()
        if not p.exists() or p.read_text(encoding="utf-8") != content
    )
    extra = sorted(str(p.relative_to(REPO)) for p in existing - set(expected))

    if args.check:
        for path in stale:
            print(f"stale: {path}")
        for path in extra:
            print(f"unexpected: {path}")
        if stale or extra:
            print("run: python3 skills/sync-references.py")
            return 1
        print("references are up to date")
        return 0

    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for rel in extra:
        (REPO / rel).unlink()
    print(f"wrote {len(expected)} files, removed {len(extra)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
