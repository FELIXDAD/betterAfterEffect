//! The QuickJS side: one runtime per run (memory and time limits), the AE
//! object model (`prelude.js`) and the single host function `__host`.

use std::cell::Cell;
use std::fmt::Write;
use std::sync::OnceLock;
use std::time::{Duration, Instant};

use rquickjs::context::EvalOptions;
use rquickjs::{CatchResultExt, CaughtError, Context, Ctx, Function, Module, Runtime};
use serde_json::Value as Json;

use crate::host::{self, RunState};

const PRELUDE: &str = include_str!("prelude.js");

/// File name of the user's script in QuickJS stack traces (to find the line).
const SCRIPT_FILE: &str = "script";

/// QuickJS heap per run.
const MEMORY_LIMIT: usize = 128 << 20;
/// Native stack QuickJS may use: deep recursion is a RangeError, never a crash,
/// also on the 1 MiB main thread of Windows.
const JS_STACK: usize = 384 << 10;

thread_local! {
    /// The run in progress on this thread (type-erased `*mut RunState`).
    static CURRENT: Cell<*mut ()> = const { Cell::new(std::ptr::null_mut()) };
}

/// Clears [`CURRENT`] when the run ends, also on panic.
struct Current;

impl Current {
    fn set(state: &mut RunState<'_, '_, '_>) -> Current {
        CURRENT.with(|c| c.set(std::ptr::from_mut(state).cast()));
        Current
    }
}

impl Drop for Current {
    fn drop(&mut self) {
        CURRENT.with(|c| c.set(std::ptr::null_mut()));
    }
}

fn with_state<T>(f: impl FnOnce(&mut RunState<'_, '_, '_>) -> T) -> Option<T> {
    let ptr = CURRENT.with(Cell::get);
    if ptr.is_null() {
        return None;
    }
    // SAFETY: `ptr` was set by `Current::set` from a `&mut RunState` that outlives
    // the evaluation (the guard is dropped before the state), on this thread.
    // Host calls are not re-entrant (commands never call back into JavaScript),
    // so this is the only live reference while `f` runs; the erased lifetimes
    // are only used inside `f`.
    let state = unsafe { &mut *ptr.cast::<RunState<'_, '_, '_>>() };
    Some(f(state))
}

fn throw<T>(ctx: &Ctx<'_>, msg: &str) -> rquickjs::Result<T> {
    Err(rquickjs::Exception::throw_message(ctx, msg))
}

fn install_host(ctx: &Ctx<'_>) -> rquickjs::Result<()> {
    let f = Function::new(ctx.clone(), |ctx: Ctx<'_>, method: String, args: String| {
        let args: Json = serde_json::from_str(&args).unwrap_or(Json::Null);
        match with_state(|s| host::call(s, &method, &args)) {
            Some(Ok(out)) => Ok(out.to_string()),
            Some(Err(e)) => throw(&ctx, &e),
            None => throw(&ctx, "no script is running"),
        }
    })?;
    ctx.globals().set("__host", f)
}

/// ExtendScript preprocessor lines (`#target aftereffects`, `#include`,
/// `#targetengine`, `#strict`) are blanked, keeping line numbers.
fn strip_directives(source: &str) -> String {
    source
        .lines()
        .map(|l| {
            if l.trim_start().starts_with('#') {
                ""
            } else {
                l
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn describe(e: CaughtError<'_>, timed_out: Option<Duration>) -> String {
    if let Some(limit) = timed_out {
        return format!(
            "the script was stopped after {:.1} seconds",
            limit.as_secs_f64()
        );
    }
    match e {
        CaughtError::Exception(ex) => {
            let msg = ex.message().unwrap_or_default();
            let name = ex
                .get::<_, String>("name")
                .unwrap_or_else(|_| "Error".to_owned());
            let line = ex.stack().and_then(|s| {
                let i = s.find(&format!("{SCRIPT_FILE}:"))?;
                let digits: String = s[i + SCRIPT_FILE.len() + 1..]
                    .chars()
                    .take_while(char::is_ascii_digit)
                    .collect();
                digits.parse::<usize>().ok()
            });
            match line {
                Some(l) => format!("{name} at line {l}: {msg}"),
                None => format!("{name}: {msg}"),
            }
        }
        CaughtError::Value(v) => format!(
            "Error: {}",
            v.as_string()
                .and_then(|s| s.to_string().ok())
                .unwrap_or_else(|| format!("{v:?}"))
        ),
        CaughtError::Error(e) => e.to_string(),
    }
}

pub(crate) enum Program<'a> {
    File(&'a str),
    Module(crate::ModuleEntry<'a>),
}

/// Bytecode generated by this process with its own QuickJS build.
#[derive(Debug)]
pub struct CompiledModule(Vec<u8>);

impl CompiledModule {
    fn from_module(module: &Module<'_>) -> rquickjs::Result<Self> {
        module.write(Default::default()).map(Self)
    }

    fn load<'js>(&self, ctx: &Ctx<'js>) -> rquickjs::Result<Module<'js>> {
        // SAFETY: only from_module constructs these bytes. They are immutable and
        // the installed package (or static host module) outlives the JS runtime.
        unsafe { Module::load(ctx.clone(), &self.0) }
    }
}

struct HostCode {
    api: CompiledModule,
    caller: CompiledModule,
}

fn host_code() -> Result<&'static HostCode, String> {
    static HOST: OnceLock<Result<HostCode, String>> = OnceLock::new();
    HOST.get_or_init(|| {
        let rt = Runtime::new().map_err(|e| e.to_string())?;
        rt.set_memory_limit(MEMORY_LIMIT);
        rt.set_max_stack_size(JS_STACK);
        Context::full(&rt).map_err(|e| e.to_string())?.with(|ctx| {
            let compile = || -> rquickjs::Result<HostCode> {
                let api = Module::declare(ctx.clone(), "bae", PRELUDE)?;
                // The caller imports the actual plugin in each invocation's runtime.
                // Wrapping its namespace also keeps an export named "then" callable.
                Module::declare(ctx.clone(), SCRIPT_FILE, "")?;
                let caller = Module::declare(
                    ctx.clone(),
                    "bae-call",
                    "export * as entries from 'script';",
                )?;
                Ok(HostCode {
                    api: CompiledModule::from_module(&api)?,
                    caller: CompiledModule::from_module(&caller)?,
                })
            };
            compile().catch(&ctx).map_err(|e| describe(e, None))
        })
    })
    .as_ref()
    .map_err(Clone::clone)
}

/// Prepares the shared AE scripting prelude for file scripts and installed plugins.
pub fn prewarm() -> Result<(), String> {
    host_code().map(|_| ())
}

/// Compiles the module and links all declared entries before the package is published.
pub fn prepare_module<'a>(
    source: &str,
    heap_bytes: usize,
    exports: impl Iterator<Item = &'a str>,
) -> Result<CompiledModule, String> {
    let host = host_code()?;
    let rt = Runtime::new().map_err(|e| e.to_string())?;
    rt.set_memory_limit(heap_bytes);
    rt.set_max_stack_size(JS_STACK);
    let context = Context::full(&rt).map_err(|e| e.to_string())?;
    context.with(|ctx| {
        // ES modules link all imports first, then evaluate dependencies in source order.
        // The first dependency stops evaluation before the plugin can run.
        let mut probe = String::from("import 'check-stop';\nimport {");
        for (i, name) in exports.enumerate() {
            write!(probe, "{} as entry{i},", Json::from(name)).unwrap();
        }
        write!(probe, "}} from '{SCRIPT_FILE}';").unwrap();
        host.api
            .load(&ctx)
            .catch(&ctx)
            .map_err(|e| describe(e, None))?;
        let compiled = Module::declare(ctx.clone(), SCRIPT_FILE, source)
            .and_then(|m| CompiledModule::from_module(&m))
            .catch(&ctx)
            .map_err(|e| describe(e, None))?;
        let check = || -> rquickjs::Result<()> {
            Module::declare(ctx.clone(), "check-stop", "throw null;")?;
            Module::evaluate(ctx.clone(), "check-exports", probe)?.finish()
        };
        match check().catch(&ctx) {
            Err(CaughtError::Value(v)) if v.is_null() => Ok(compiled),
            Err(e) => Err(describe(e, None)),
            Ok(()) => Err("module validation did not stop before evaluation".into()),
        }
    })
}

impl Program<'_> {
    fn eval<'js>(&self, ctx: &Ctx<'js>, host: &HostCode) -> rquickjs::Result<rquickjs::Value<'js>> {
        match self {
            Self::File(source) => {
                let mut opts = EvalOptions::default();
                opts.global = true;
                opts.strict = false;
                opts.filename = Some(SCRIPT_FILE.into());
                ctx.eval_with_options(strip_directives(source), opts)
            }
            Self::Module(entry) => {
                entry.module.load(ctx)?;
                host.caller.load(ctx)?;
                let caller: rquickjs::Object = Module::import(ctx, "bae-call")?.finish()?;
                let entries: rquickjs::Object = caller.get("entries")?;
                let function: Function<'_> = entries.get(entry.export)?;
                let result = function.call((ctx.json_parse(entry.args.to_string())?,))?;
                rquickjs::promise::MaybePromise::from_value(result).finish()
            }
        }
    }
}

pub(crate) fn execute(
    state: &mut RunState<'_, '_, '_>,
    program: Program<'_>,
) -> Result<Json, String> {
    if !CURRENT.with(Cell::get).is_null() {
        return Err("a script cannot run another script".into());
    }
    let rt = Runtime::new().map_err(|e| e.to_string())?;
    rt.set_memory_limit(match &program {
        Program::File(_) => MEMORY_LIMIT,
        Program::Module(entry) => entry.heap_bytes,
    });
    rt.set_max_stack_size(JS_STACK);
    let limit = state.env.time_limit.unwrap_or(crate::TIME_LIMIT);
    let deadline = Instant::now() + limit;
    rt.set_interrupt_handler(Some(Box::new(move || Instant::now() >= deadline)));
    let ctx = Context::full(&rt).map_err(|e| e.to_string())?;
    let _current = Current::set(state);
    ctx.with(|ctx| {
        install_host(&ctx).map_err(|e| e.to_string())?;
        let host = host_code()?;
        host.api
            .load(&ctx)
            .and_then(|m| m.eval()?.1.finish::<()>())
            .catch(&ctx)
            .map_err(|e| format!("script prelude: {}", describe(e, None)))?;
        let text = program
            .eval(&ctx, host)
            .and_then(|value| {
                ctx.json_stringify(value)?
                    .map(|s| s.to_string())
                    .transpose()
            })
            .catch(&ctx)
            .map_err(|e| describe(e, (Instant::now() >= deadline).then_some(limit)))?;
        serde_json::from_str(text.as_deref().unwrap_or("null")).map_err(|e| e.to_string())
    })
}
