pub(super) const MASK: &[&str] = &["Color/Gray", "Color/Black", "White/Black"];

pub(super) fn localize(fx: &mut Builtin) {
    for (ids, menu) in [
        (&[5, 127][..], INPUT),
        (&[25, 128], LOOK),
        (&[130], SPACES),
        (&[75], MASK),
    ] {
        let labels: Vec<String> = menu
            .iter()
            .map(|label| {
                match *label {
                    "None" => "无",
                    "[Custom]" => "[自定义]",
                    "Browse..." => "浏览...",
                    "Color/Gray" => "彩色/灰色",
                    "Color/Black" => "彩色/黑色",
                    "White/Black" => "白色/黑色",
                    other => other,
                }
                .to_owned()
            })
            .collect();
        for &id in ids {
            fx.info.param_options_zh.push((id, labels.clone()));
        }
    }
}
